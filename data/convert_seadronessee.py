"""
Convert SeaDronesSee (and MOBDrone / AFO) COCO-style annotations to YOLO format.

SeaDronesSee Object Detection v2 ships COCO-style JSON:
    annotations/instances_train.json
    annotations/instances_val.json
    images/<split>/*.jpg
Each annotation has bbox = [x, y, w, h] in absolute pixels and a category_id.

This script:
  1. reads the COCO JSON,
  2. writes one YOLO .txt per image  ( "<cls> <cx> <cy> <w> <h>"  normalised 0-1 ),
  3. writes a data.yaml usable by Ultralytics.

Two label schemes (``--scheme``):
  * "native"  — keep all original categories (6 for SeaDronesSee OD v2:
                swimmer, floater, boat, swimmer-on-boat, floater-on-boat, life-jacket).
  * "binary"  — collapse to {0: person, 1: boat}; everything that is not a boat
                becomes "person". This matches the SeaDronesSee supercategories and
                is the cleanest target for a SAR "human in water" detector.

Stdlib only — no third-party deps, so it runs anywhere (incl. inside the
SageMaker processing job).

Usage:
  python convert_seadronessee.py \
      --coco-json  data/seadronessee/annotations/instances_train.json \
      --images-dir data/seadronessee/images/train \
      --out-dir    data/sds_yolo/train \
      --scheme     binary
"""

import argparse
import json
import os
from collections import defaultdict

# Category-name -> binary class.  Anything not matched here that is NOT a boat
# is treated as person.  Matching is case-insensitive substring.
_BOAT_KEYS = ("boat", "vessel", "ship")


def _is_boat(name: str) -> bool:
    n = name.lower()
    return any(k in n for k in _BOAT_KEYS)


def build_category_map(categories, scheme):
    """Return (catid -> yolo_class_index, list_of_class_names)."""
    if scheme == "native":
        # Stable, contiguous indices ordered by original category id.
        ordered = sorted(categories, key=lambda c: c["id"])
        catid_to_idx = {c["id"]: i for i, c in enumerate(ordered)}
        names = [c["name"] for c in ordered]
        return catid_to_idx, names

    if scheme == "binary":
        # 0 = person, 1 = boat
        catid_to_idx = {}
        for c in categories:
            catid_to_idx[c["id"]] = 1 if _is_boat(c["name"]) else 0
        return catid_to_idx, ["person", "boat"]

    raise ValueError(f"unknown scheme {scheme!r}")


def convert(coco_json, images_dir, out_dir, scheme, write_yaml=True):
    with open(coco_json) as f:
        coco = json.load(f)

    images = {im["id"]: im for im in coco["images"]}
    catid_to_idx, names = build_category_map(coco["categories"], scheme)

    # group annotations by image
    anns_by_img = defaultdict(list)
    for a in coco["annotations"]:
        anns_by_img[a["image_id"]].append(a)

    labels_dir = os.path.join(out_dir, "labels")
    os.makedirs(labels_dir, exist_ok=True)

    n_imgs, n_boxes, n_skipped = 0, 0, 0
    for img_id, im in images.items():
        w_img, h_img = im["width"], im["height"]
        stem = os.path.splitext(os.path.basename(im["file_name"]))[0]
        lines = []
        for a in anns_by_img.get(img_id, []):
            if a.get("iscrowd", 0):
                continue
            x, y, bw, bh = a["bbox"]
            if bw <= 0 or bh <= 0:
                n_skipped += 1
                continue
            cls = catid_to_idx.get(a["category_id"])
            if cls is None:
                n_skipped += 1
                continue
            # COCO bbox -> YOLO normalised centre form, clamped to [0,1]
            cx = min(max((x + bw / 2) / w_img, 0.0), 1.0)
            cy = min(max((y + bh / 2) / h_img, 0.0), 1.0)
            nw = min(bw / w_img, 1.0)
            nh = min(bh / h_img, 1.0)
            lines.append(f"{cls} {cx:.6f} {cy:.6f} {nw:.6f} {nh:.6f}")
            n_boxes += 1
        # write even empty files (negative images help suppress sea-clutter FPs)
        with open(os.path.join(labels_dir, stem + ".txt"), "w") as f:
            f.write("\n".join(lines))
        n_imgs += 1

    print(f"[convert] {n_imgs} label files, {n_boxes} boxes, "
          f"{n_skipped} skipped  ->  {labels_dir}")
    print(f"[convert] classes ({scheme}): {names}")

    if write_yaml:
        _write_dataset_yaml(out_dir, images_dir, names)
    return names


def _write_dataset_yaml(out_dir, images_dir, names):
    """Minimal Ultralytics data.yaml. Assumes train/val dirs created separately;
    here we point train+val at the same images_dir for a single-split convert.
    Edit paths after converting both splits."""
    yaml_path = os.path.join(out_dir, "data.yaml")
    names_block = "\n".join(f"  {i}: {n}" for i, n in enumerate(names))
    with open(yaml_path, "w") as f:
        f.write(
            f"# Auto-generated by convert_seadronessee.py\n"
            f"path: {os.path.abspath(os.path.dirname(out_dir))}\n"
            f"train: {os.path.abspath(images_dir)}\n"
            f"val: {os.path.abspath(images_dir)}\n"
            f"nc: {len(names)}\n"
            f"names:\n{names_block}\n"
        )
    print(f"[convert] wrote {yaml_path}  (edit train/val paths for your split layout)")


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--coco-json", required=True)
    p.add_argument("--images-dir", required=True)
    p.add_argument("--out-dir", required=True)
    p.add_argument("--scheme", default="binary", choices=["binary", "native"])
    p.add_argument("--no-yaml", action="store_true")
    return p.parse_args()


if __name__ == "__main__":
    a = parse_args()
    convert(a.coco_json, a.images_dir, a.out_dir, a.scheme, write_yaml=not a.no_yaml)
